export const devT = (lang: Locale, key: string, vars?: Record<string, string | number>) => {
  let str = DEV_I18N[lang]?.[key] ?? DEV_I18N.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
};
